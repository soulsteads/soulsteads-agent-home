#!/usr/bin/env bash
# Build and qualify a Debian 13-compatible binary package from this checkout.
set -euo pipefail

ROOT=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)
OUT_DIR="$ROOT/dist/debian"
DPKG_DEB=${DPKG_DEB:-dpkg-deb}
PACKAGE=soulsteads-agent-home
PROJECT=soulsteads
MODULE=soulsteads
ENTRYPOINT=soulsteads
ENTRY_TARGET=soulsteads.cli:main
DEPENDS='python3 (>= 3.11), git'
RECOMMENDS='python3-yaml, python3-tomlkit, python3-secretstorage'

usage() {
    printf 'Usage: %s [--out-dir DIRECTORY]\n' "${0##*/}"
}

while (($#)); do
    case "$1" in
        --out-dir)
            (($# >= 2)) || { usage >&2; exit 2; }
            OUT_DIR=$2
            shift 2
            ;;
        --help|-h)
            usage
            exit 0
            ;;
        *)
            usage >&2
            exit 2
            ;;
    esac
done

command -v uv >/dev/null || { echo 'uv is required to build the wheel' >&2; exit 1; }
command -v "$DPKG_DEB" >/dev/null || { echo 'dpkg-deb is required to build the Debian package' >&2; exit 1; }

mkdir -p -- "$OUT_DIR"
OUT_DIR=$(cd -- "$OUT_DIR" && pwd -P)
work=$(mktemp -d "${TMPDIR:-/tmp}/soulsteads-agent-home-deb.XXXXXXXX")
trap 'rm -rf -- "$work"' EXIT
wheel_dir="$work/wheel"
stage="$work/stage"
extract="$work/extract"
smoke_home="$work/home"
smoke_cwd="$work/smoke"
mkdir -p -- "$wheel_dir" "$stage/DEBIAN" "$stage/usr/lib/python3/dist-packages" \
    "$stage/usr/bin" "$stage/usr/share/doc/$PACKAGE" "$smoke_home" "$smoke_cwd"

# Build the actual wheel; Debian dependencies are intentionally not vendored.
(
    cd -- "$ROOT"
    uv build --wheel --out-dir "$wheel_dir"
)
shopt -s nullglob
wheels=("$wheel_dir"/*.whl)
(( ${#wheels[@]} == 1 )) || { echo 'expected exactly one wheel' >&2; exit 1; }
wheel=${wheels[0]}

# Extract only the wheel's Python payload, rejecting links and traversal entries.
python3 -I - "$wheel" "$stage/usr/lib/python3/dist-packages" <<'PY'
import stat
import sys
import zipfile
from pathlib import Path, PurePosixPath

wheel, destination = map(Path, sys.argv[1:])
with zipfile.ZipFile(wheel) as archive:
    for info in archive.infolist():
        path = PurePosixPath(info.filename)
        if path.is_absolute() or '..' in path.parts or not path.parts:
            raise SystemExit(f'unsafe wheel member: {info.filename!r}')
        if stat.S_ISLNK(info.external_attr >> 16):
            raise SystemExit(f'wheel link is not allowed: {info.filename!r}')
        parts = path.parts
        if parts[0].endswith('.data'):
            if len(parts) < 3 or parts[1] not in {'purelib', 'platlib'}:
                continue
            parts = parts[2:]
        if not parts or info.is_dir():
            continue
        target = destination.joinpath(*parts)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(archive.read(info))
        target.chmod(0o644)
PY

test -f "$stage/usr/lib/python3/dist-packages/$MODULE/__init__.py"
debian_version=$(python3 -I "$ROOT/scripts/debian-version.py" "$stage/usr/lib/python3/dist-packages" "$PROJECT")
# Encode an epoch for the artifact filename (the Debian control field keeps ':').
filename_version=${debian_version//:/%3a}

cat > "$stage/usr/bin/$ENTRYPOINT" <<EOF
#!/usr/bin/python3
# Generated by $PACKAGE; this package owns no system service.
from ${ENTRY_TARGET%:*} import ${ENTRY_TARGET#*:}

if __name__ == "__main__":
    raise SystemExit(${ENTRY_TARGET#*:}())
EOF
chmod 0755 "$stage/usr/bin/$ENTRYPOINT"

cat > "$stage/DEBIAN/control" <<EOF
Package: $PACKAGE
Version: $debian_version
Section: utils
Priority: optional
Architecture: all
Maintainer: Soulsteads
Depends: $DEPENDS
Recommends: $RECOMMENDS
Description: Portable local agent-home definition CLI
 Create and manage local, Git-tracked agent homes without installing or
 activating a runtime service.
EOF
{
    cat <<'EOF'
Format: https://www.debian.org/doc/packaging-manuals/copyright-format/1.0/
Upstream-Name: Soulsteads Agent Home
Source: https://github.com/soulsteads/soulsteads-agent-home
Files: *
Copyright: 2026 Soulsteads
License: Apache-2.0

EOF
    cat "$ROOT/LICENSE"
} > "$stage/usr/share/doc/$PACKAGE/copyright"
install -m 0644 "$ROOT/NOTICE" "$stage/usr/share/doc/$PACKAGE/NOTICE"

# A binary package must remain inert: no maintainer scripts, units, or activation hooks.
test ! -e "$stage/DEBIAN/preinst"
test ! -e "$stage/DEBIAN/postinst"
test ! -e "$stage/DEBIAN/prerm"
test ! -e "$stage/DEBIAN/postrm"

package_file="$OUT_DIR/${PACKAGE}_${filename_version}_all.deb"
rm -f -- "$package_file"
"$DPKG_DEB" --build --root-owner-group "$stage" "$package_file" >/dev/null

control=$("$DPKG_DEB" -f "$package_file")
grep -Fx "Package: $PACKAGE" <<<"$control" >/dev/null
grep -Fx "Version: $debian_version" <<<"$control" >/dev/null
grep -Fx "Depends: $DEPENDS" <<<"$control" >/dev/null
grep -Fx "Recommends: $RECOMMENDS" <<<"$control" >/dev/null
"$DPKG_DEB" -x "$package_file" "$extract"
test -f "$extract/usr/lib/python3/dist-packages/$MODULE/cli.py"
test -f "$extract/usr/share/doc/$PACKAGE/copyright"
test -f "$extract/usr/share/doc/$PACKAGE/NOTICE"
test ! -e "$extract/lib/systemd"
test ! -e "$extract/usr/lib/systemd"
# Run only extracted bytes, from outside the source checkout and with an isolated home.
(
    cd -- "$smoke_cwd"
    env -i PATH="/usr/bin:/bin" HOME="$smoke_home" PYTHONNOUSERSITE=1 \
        PYTHONPATH="$extract/usr/lib/python3/dist-packages" \
        "$extract/usr/bin/$ENTRYPOINT" --help >/dev/null
    env -i PATH="/usr/bin:/bin" HOME="$smoke_home" PYTHONNOUSERSITE=1 \
        PYTHONPATH="$extract/usr/lib/python3/dist-packages" \
        /usr/bin/python3 -c 'import importlib, pathlib, sys; module = importlib.import_module(sys.argv[1]); assert pathlib.Path(module.__file__).resolve().is_relative_to(pathlib.Path(sys.argv[2]).resolve())' \
        "$MODULE" "$extract/usr/lib/python3/dist-packages"
)
printf '%s\n' "$package_file"
